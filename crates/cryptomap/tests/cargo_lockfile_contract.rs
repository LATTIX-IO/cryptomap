//! FOSS-322.2 end-to-end scoped Cargo.lock collector regression and security.
#![allow(clippy::unwrap_used, clippy::expect_used)]
use cryptomap::{
    AssetKind, CollectionRunId, CoverageState, IdentityContext, InventoryLimits,
    collector::{
        CancellationToken, CollectionRequest, CollectionStatus, Collector, RequestedSource,
    },
    collectors::dependency::cargo::CargoLockfileCollector,
    coverage::CollectionScopeId,
    orchestration::{ScopedInvocation, collect_normalized},
    pipeline::PipelineInput,
    raw::{RawFactKind, RawLimits, RawSourceKind},
    registry::Registry,
    scope::{CollectionScope, collect_scoped},
};
use std::{
    collections::BTreeMap,
    fs,
    path::PathBuf,
    sync::atomic::{AtomicUsize, Ordering},
};

static NEXT: AtomicUsize = AtomicUsize::new(0);
const VALID: &str = "# generated by Cargo\nversion = 4\n\n[[package]]\nname = \"ring\"\nversion = \"0.17.12\"\nsource = \"registry+https://example.invalid/index\"\nchecksum = \"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\"\ndependencies = [\n \"getrandom\",\n]\n\n[[package]]\nname = \"local-app\"\nversion = \"0.1.0\"\n";

struct Fixture {
    root: PathBuf,
}
impl Fixture {
    fn new(documents: &[(&str, &str)]) -> Self {
        let index = NEXT.fetch_add(1, Ordering::Relaxed);
        let root =
            std::env::temp_dir().join(format!("cryptomap-cargo-{}-{index}", std::process::id()));
        fs::create_dir_all(&root).unwrap();
        for (path, content) in documents {
            fs::write(root.join(path), content).unwrap();
        }
        Self { root }
    }
    fn scope(&self, items: &[(&str, &str)], tenant: &str) -> CollectionScope {
        let mut scope = CollectionScope::new(CollectionScopeId::new(tenant).unwrap());
        for (id, path) in items {
            scope
                .grant_file(
                    RawSourceKind::Dependency,
                    *id,
                    &self.root,
                    path,
                    32 * 1024,
                )
                .unwrap();
        }
        scope
    }
}
impl Drop for Fixture {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.root);
    }
}

fn sources(items: &[&str]) -> Vec<RequestedSource> {
    items
        .iter()
        .map(|item| RequestedSource {
            kind: RawSourceKind::Dependency,
            item: (*item).into(),
        })
        .collect()
}
fn request(run: &str, items: &[&str]) -> CollectionRequest {
    CollectionRequest {
        run: CollectionRunId::new(run).unwrap(),
        sources: sources(items),
        limits: RawLimits::default(),
        options: BTreeMap::new(),
    }
}

#[test]
fn cargo_packages_are_evidence_backed_without_algorithm_use_inference() {
    let fixture = Fixture::new(&[("Cargo.lock", VALID)]);
    let scope = fixture.scope(&[("cargo:lock", "Cargo.lock")], "tenant-a");
    let collector = CargoLockfileCollector::new(&scope, "2026-10-11T12:00:00Z");
    let cancel = CancellationToken::default();
    let one = collect_scoped(&scope, &collector, request("run-1", &["cargo:lock"]), &cancel)
        .unwrap();
    let two = collect_scoped(&scope, &collector, request("run-1", &["cargo:lock"]), &cancel)
        .unwrap();
    assert_eq!(one, two);
    assert_eq!(one.status, CollectionStatus::Complete);
    assert_eq!(one.coverage["cargo:lock"], CoverageState::InspectedObserved);
    assert_eq!(one.observations.len(), 2);
    assert!(one.observations.iter().all(|observation| {
        matches!(observation.fact, RawFactKind::Dependency { .. })
            && observation.source_sha256.as_ref().map(String::len) == Some(64)
    }));
    let ring = one
        .observations
        .iter()
        .find(|observation| matches!(&observation.fact, RawFactKind::Dependency { name, .. } if name == "ring"))
        .unwrap();
    assert_eq!(
        ring.attributes
            .get("cargo:source-sha256")
            .map(String::len),
        Some(64)
    );
    assert!(!format!("{ring:?}").contains("example.invalid"));

    let registry = Registry::builtin();
    let identity = IdentityContext::new("tenant-a").unwrap();
    let run = CollectionRunId::new("run-1").unwrap();
    let expected_descriptor = collector.descriptor();
    let requested = sources(&["cargo:lock"]);
    let snapshot = collect_normalized(
        ScopedInvocation {
            collector: &collector,
            input: PipelineInput {
                scope: &scope,
                identity: &identity,
                registry: &registry,
                expected_descriptor: &expected_descriptor,
                expected_run: &run,
                sources: &requested,
                raw_limits: RawLimits::default(),
                inventory_limits: InventoryLimits::default(),
                started_at: "2026-10-11T11:59:00Z",
                ended_at: "2026-10-11T12:01:00Z",
            },
        },
        &cancel,
    )
    .unwrap();
    assert_eq!(snapshot.assets.len(), 2);
    assert_eq!(snapshot.observations.len(), 2);
    assert_eq!(snapshot.evidence.len(), 2);
    assert!(snapshot
        .assets
        .values()
        .all(|asset| matches!(asset.kind, AssetKind::Library { .. })));
    snapshot
        .verify_for_scope(scope.id(), InventoryLimits::default())
        .unwrap();
}

#[test]
fn unsupported_one_source_retains_successful_sibling_without_fabricated_absence() {
    let invalid = "version = 99\n[[package]]\nname = \"ignored\"\nversion = \"1\"\n";
    let fixture = Fixture::new(&[("Cargo.lock", VALID), ("bad.lock", invalid)]);
    let scope = fixture.scope(
        &[("cargo:valid", "Cargo.lock"), ("cargo:bad", "bad.lock")],
        "tenant-a",
    );
    let collector = CargoLockfileCollector::new(&scope, "2026-10-11T12:00:00Z");
    let result = collect_scoped(
        &scope,
        &collector,
        request("run-2", &["cargo:bad", "cargo:valid"]),
        &CancellationToken::default(),
    )
    .unwrap();
    assert_eq!(result.status, CollectionStatus::Partial);
    assert_eq!(result.observations.len(), 2);
    assert_eq!(result.coverage["cargo:bad"], CoverageState::Failed);
    assert_eq!(
        result.coverage["cargo:valid"],
        CoverageState::InspectedObserved
    );
    assert_eq!(result.diagnostics.len(), 1);
}

#[test]
fn unauthorized_file_and_size_limit_cannot_establish_success_coverage() {
    let fixture = Fixture::new(&[("Cargo.lock", VALID)]);
    let scope = CollectionScope::new(CollectionScopeId::new("tenant-a").unwrap());
    let collector = CargoLockfileCollector::new(&scope, "2026-10-11T12:00:00Z");
    assert!(collect_scoped(
        &scope,
        &collector,
        request("run-3", &["cargo:lock"]),
        &CancellationToken::default(),
    )
    .is_err());

    let mut small = CollectionScope::new(CollectionScopeId::new("tenant-a").unwrap());
    small
        .grant_file(
            RawSourceKind::Dependency,
            "cargo:lock",
            &fixture.root,
            "Cargo.lock",
            8,
        )
        .unwrap();
    assert!(small
        .open_file(RawSourceKind::Dependency, "cargo:lock")
        .and_then(|file| file.read_bounded())
        .is_err());
    let collector = CargoLockfileCollector::new(&small, "2026-10-11T12:00:00Z");
    let outcome = collect_scoped(
        &small,
        &collector,
        request("run-4", &["cargo:lock"]),
        &CancellationToken::default(),
    )
    .unwrap();
    assert!(outcome.observations.is_empty());
    assert_eq!(outcome.coverage["cargo:lock"], CoverageState::Failed);
}

#[test]
fn malformed_binary_duplicate_fields_and_truncated_arrays_fail_closed() {
    for input in [
        "version = 4\n[[package]]\nname = \"a\"\nname = \"b\"\nversion = \"1\"\n",
        "version = 4\n[[package]]\nname = \"a\"\nversion = \"1\"\ndependencies = [\n \"b\",\n",
        "version = 4\n[[package]]\nname = \"a\"\nversion = \"1\"\n[[other]]\n",
        "version = 4\n[[package]]\nname = \"a\"\n",
    ] {
        let fixture = Fixture::new(&[("Cargo.lock", input)]);
        let scope = fixture.scope(&[("cargo:lock", "Cargo.lock")], "tenant-a");
        let collector = CargoLockfileCollector::new(&scope, "2026-10-11T12:00:00Z");
        let result = collect_scoped(
            &scope,
            &collector,
            request("run-invalid", &["cargo:lock"]),
            &CancellationToken::default(),
        )
        .unwrap();
        assert_eq!(result.status, CollectionStatus::Failed);
        assert_eq!(result.coverage["cargo:lock"], CoverageState::Failed);
        assert!(result.observations.is_empty());
        assert_eq!(result.diagnostics.len(), 1);
    }
}

#[test]
fn cancellation_produces_no_false_inspection() {
    let fixture = Fixture::new(&[("Cargo.lock", VALID)]);
    let scope = fixture.scope(&[("cargo:lock", "Cargo.lock")], "tenant-a");
    let collector = CargoLockfileCollector::new(&scope, "2026-10-11T12:00:00Z");
    let cancel = CancellationToken::default();
    cancel.cancel();
    let result = collect_scoped(
        &scope,
        &collector,
        request("run-cancelled", &["cargo:lock"]),
        &cancel,
    )
    .unwrap();
    assert_eq!(result.coverage["cargo:lock"], CoverageState::NotInspected);
    assert!(result.observations.is_empty());
}
